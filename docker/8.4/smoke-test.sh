#!/usr/bin/env bash
#
# Smoke test for the production PHP image (Dockerfile target `production`).
#
#   docker/8.4/smoke-test.sh IMAGE [PLATFORM]
#
# PLATFORM defaults to the host's own (linux/amd64 or linux/arm64). The image is
# run natively, so PLATFORM must match the host: build and test each architecture
# on its own runner. Exits 0 only if every assertion holds; each failure prints
# the reason. Everything the script creates (containers, one volume) carries a
# unique name and is removed on exit.

set -uo pipefail

IMAGE="${1:-}"
if [[ -z "$IMAGE" ]]; then
    echo "usage: $0 IMAGE [PLATFORM]" >&2
    exit 2
fi

case "$(uname -m)" in
    x86_64 | amd64) HOST_ARCH=amd64 ;;
    aarch64 | arm64) HOST_ARCH=arm64 ;;
    *) HOST_ARCH="$(uname -m)" ;;
esac
PLATFORM="${2:-linux/${HOST_ARCH}}"
WANT_ARCH="${PLATFORM#linux/}"
case "$WANT_ARCH" in
    amd64) WANT_UNAME=x86_64 ;;
    arm64) WANT_UNAME=aarch64 ;;
    *) echo "unsupported platform: $PLATFORM" >&2; exit 2 ;;
esac
if [[ "$WANT_ARCH" != "$HOST_ARCH" ]]; then
    echo "platform $PLATFORM does not match this host ($HOST_ARCH); run the smoke test on a native $WANT_ARCH runner" >&2
    exit 2
fi

APP_DIR=/var/www/html
SUFFIX="$$-$(date +%s)"
WEB_CONTAINER="wxnotify-smoke-web-${SUFFIX}"
STORAGE_VOLUME="wxnotify-smoke-storage-${SUFFIX}"
FAILURES=0
VOLUME_CREATED=0

cleanup() {
    docker stop "$WEB_CONTAINER" >/dev/null 2>&1 || true
    if [[ "$VOLUME_CREATED" == 1 ]]; then
        docker volume rm "$STORAGE_VOLUME" >/dev/null 2>&1 || true
    fi
}
trap cleanup EXIT

pass() { echo "PASS $1"; }
fail() {
    echo "FAIL $1" >&2
    FAILURES=$((FAILURES + 1))
}

# Every one-off command runs through the image's own entrypoint, on the requested
# platform, and is removed on exit. The entrypoint prints notices on stdout, so
# results are read from lines with a known shape or a "=> " marker.
run() { docker run --rm --platform "$PLATFORM" -e SHOW_WELCOME_MESSAGE=false "$@"; }
marked() { sed -n 's/^=> //p'; }
package_names() { grep -E '^[a-z0-9_.-]+/[a-z0-9_.-]+$'; }

if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
    echo "FAIL image $IMAGE does not exist (build it with: docker build -f docker/8.4/Dockerfile --target production -t $IMAGE .)" >&2
    exit 1
fi

# (g) Architecture: the image's metadata and what it actually runs.
image_arch="$(docker image inspect "$IMAGE" --format '{{.Architecture}}')"
running_uname="$(run "$IMAGE" uname -m 2>/dev/null | tail -n 1)"
if [[ "$image_arch" == "$WANT_ARCH" && "$running_uname" == "$WANT_UNAME" ]]; then
    pass "(g) architecture: image $image_arch, uname -m $running_uname, requested $PLATFORM"
else
    fail "(g) architecture: image $image_arch, uname -m '$running_uname', requested $PLATFORM (expected $WANT_UNAME)"
fi

# Image configuration: runs as www-data, OPcache on, health check on /up, no automation baked in.
image_user="$(docker image inspect "$IMAGE" --format '{{.Config.User}}')"
image_env="$(docker image inspect "$IMAGE" --format '{{range .Config.Env}}{{println .}}{{end}}')"
if [[ "$image_user" == "www-data" ]] \
    && grep -qx 'PHP_OPCACHE_ENABLE=1' <<<"$image_env" \
    && grep -qx 'HEALTHCHECK_PATH=/up' <<<"$image_env" \
    && ! grep -q '^AUTORUN_' <<<"$image_env"; then
    pass "image config: user www-data, PHP_OPCACHE_ENABLE=1, HEALTHCHECK_PATH=/up, no AUTORUN_* set"
else
    fail "image config: user '$image_user'; env: $(grep -E '^(PHP_OPCACHE_ENABLE|HEALTHCHECK_PATH|AUTORUN_)' <<<"$image_env" | tr '\n' ' ')"
fi

# An application key generated by the image itself, with no .env present.
APP_KEY="$(run "$IMAGE" php artisan key:generate --show --no-ansi 2>/dev/null | grep -E '^base64:' | tail -n 1)"
if [[ "$APP_KEY" == base64:* ]]; then
    pass "key:generate --show works with no .env"
else
    fail "key:generate --show printed no key; using a random one for the rest of the test"
    APP_KEY="base64:$(head -c 32 /dev/urandom | base64)"
fi

# (b) A command override runs that command instead of S6, so nginx never starts.
version="$(run "$IMAGE" php artisan --version --no-ansi 2>&1 | tail -n 1)"
if [[ "$version" == "Laravel Framework "* ]]; then
    pass "(b) command override: $version"
else
    fail "(b) php artisan --version printed: $version"
fi
processes="$(run "$IMAGE" sh -c 'sleep 2; for comm in /proc/[0-9]*/comm; do echo "=> $(cat "$comm")"; done 2>/dev/null' | marked | sort -u | tr '\n' ' ')"
if grep -Eqw 'nginx|php-fpm|s6-svscan' <<<"$processes"; then
    fail "(b) a command override still started a server: $processes"
else
    pass "(b) a command override starts no nginx, php-fpm or S6 (processes: $processes)"
fi

# (c) Nothing that must stay out of the image.
forbidden="$(run "$IMAGE" sh -c '
    cd '"$APP_DIR"' || exit 1
    for path in .env auth.json tests docs .git .claude .ai .superpowers .github node_modules \
        pipeline docker import deploy database/database.sqlite phpunit.xml CLAUDE.md AGENTS.md \
        boost.json .mcp.json compose.yaml compose.production.yaml package.json vite.config.js; do
        [ -e "$path" ] || [ -L "$path" ] && echo "=> '"$APP_DIR"'/$path"
    done
    ls -A | grep "^\.env" | sed "s|^|=> '"$APP_DIR"'/|"
    find / -xdev -name auth.json 2>/dev/null | sed "s|^|=> |"
    true
' 2>/dev/null | marked | sort -u | tr '\n' ' ')"
if [[ -z "${forbidden// /}" ]]; then
    pass "(c) no .env, auth.json, tests, docs, .git, .claude, .ai, node_modules, pipeline, docker, import or deploy in the image"
else
    fail "(c) present in the image: $forbidden"
fi

# (d) No dev dependencies: neither in Composer's installed list nor on disk.
installed="$(run "$IMAGE" composer show --no-dev --name-only --no-ansi 2>/dev/null | package_names)"
installed_all="$(run "$IMAGE" composer show --installed --name-only --no-ansi 2>/dev/null | package_names)"
dev_found=""
for package in pestphp/pest filament/blueprint laravel/boost laravel/pail laravel/pint fakerphp/faker mockery/mockery; do
    if grep -qx "$package" <<<"$installed" || grep -qx "$package" <<<"$installed_all"; then
        dev_found+="$package "
    fi
done
on_disk="$(run "$IMAGE" sh -c 'cd '"$APP_DIR"'/vendor && for dir in pestphp filament/blueprint laravel/boost laravel/pail laravel/pint fakerphp mockery; do [ -e "$dir" ] && echo "=> vendor/$dir"; done; true' | marked | tr '\n' ' ')"
if [[ -z "$installed_all" ]]; then
    fail "(d) composer show --installed listed nothing (is composer.json in the image?)"
elif [[ -z "$dev_found" && -z "${on_disk// /}" ]]; then
    pass "(d) no dev dependencies ($(wc -l <<<"$installed_all" | tr -d ' ') packages installed)"
else
    fail "(d) dev dependencies present: ${dev_found}${on_disk}"
fi

# (e) Built Vite assets.
if run "$IMAGE" test -f "$APP_DIR/public/build/manifest.json"; then
    pass "(e) public/build/manifest.json exists"
else
    fail "(e) public/build/manifest.json is missing"
fi

# (f) A fresh named volume on storage/ takes the image directory's ownership, so
# the container user can write to it on first start.
if docker volume create "$STORAGE_VOLUME" >/dev/null; then
    VOLUME_CREATED=1
    volume_check="$(run -v "$STORAGE_VOLUME:$APP_DIR/storage" "$IMAGE" sh -c '
        set -e
        cd '"$APP_DIR"'
        echo "=> user $(id -u):$(id -g) volume-root $(stat -c %u:%g storage)"
        echo private > storage/app/private/smoke-test.txt
        echo log > storage/logs/smoke-test.log
        php artisan tinker --execute "logger()->info(\"smoke-test log line\");" >/dev/null
        grep -q "smoke-test log line" storage/logs/laravel.log
        echo "=> written"
    ' 2>&1)"
    reread="$(run -v "$STORAGE_VOLUME:$APP_DIR/storage" "$IMAGE" cat "$APP_DIR/storage/app/private/smoke-test.txt" 2>/dev/null | tail -n 1)"
    if grep -q '^=> written$' <<<"$volume_check" && grep -q '^=> user 33:33 volume-root 33:33$' <<<"$volume_check" && [[ "$reread" == "private" ]]; then
        pass "(f) fresh named volume: $(marked <<<"$volume_check" | head -n 1); wrote storage/app/private and storage/logs (and Laravel's log) as the container user; the file persisted"
    else
        fail "(f) fresh named volume: $volume_check; reread '$reread'"
    fi
else
    fail "(f) could not create volume $STORAGE_VOLUME"
fi

# The caches ServerSideUp's automation builds on a web container start (config,
# routes, views, events) build in the image as the container user.
optimize="$(run -e APP_KEY="$APP_KEY" "$IMAGE" php artisan optimize --no-ansi 2>&1)"
if [[ $? -eq 0 ]]; then
    pass "php artisan optimize succeeds as the container user"
else
    fail "php artisan optimize: $(tail -n 5 <<<"$optimize")"
fi

# (a) The default command serves the application and becomes healthy. DB_* point
# at a host that does not exist: /up must not need the database.
if docker run -d --rm --platform "$PLATFORM" --name "$WEB_CONTAINER" \
    -e APP_KEY="$APP_KEY" -e APP_ENV=production -e APP_DEBUG=false \
    -e DB_CONNECTION=pgsql -e DB_HOST=wxnotify-smoke-no-database -e DB_PORT=5432 \
    -e DB_DATABASE=wxnotify -e DB_USERNAME=wxnotify -e DB_PASSWORD=smoke-test \
    "$IMAGE" >/dev/null; then
    status=""
    for _ in $(seq 1 60); do
        status="$(docker inspect "$WEB_CONTAINER" --format '{{.State.Health.Status}}' 2>/dev/null)"
        [[ "$status" == "healthy" || "$status" == "unhealthy" || -z "$status" ]] && break
        sleep 2
    done
    up_code="$(docker exec "$WEB_CONTAINER" curl -s -o /dev/null -w '%{http_code}' "http://localhost:8080/up" 2>/dev/null)"
    if [[ "$status" == "healthy" && "$up_code" == "200" ]]; then
        pass "(a) default command became healthy and GET /up returned 200"
    else
        fail "(a) health '$status', GET /up returned '$up_code'; last log lines:"
        docker logs --tail 30 "$WEB_CONTAINER" >&2 2>&1
    fi
else
    fail "(a) the web container did not start"
fi

if [[ "$FAILURES" -gt 0 ]]; then
    echo "$FAILURES assertion(s) failed for $IMAGE" >&2
    exit 1
fi
echo "All assertions passed for $IMAGE ($PLATFORM)"
